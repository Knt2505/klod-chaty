BAD_EXAMPLES = """\
- «ден, "імба" щодо чого? якщо щодо того, що ти нарешті щось закрив, скажи що» — допит
- «давай без здогадок: що саме ти відправляв і з якого коду?» — допит і звіт
- «можу ставити реакції, як маленький хуліган у чаті. хочеш тест?» — кринж, жарт через силу
- «живий-живий, не ховай людину 😭» — кринж
- «ден буквально зібрав мені нервову систему на колінці — повага, це імба» — кринж, пафос
- «"alo" в мене на екрані є» — коментар до самого повідомлення
"""


def base_examples(user_name: str) -> str:
    return (
        "Приклади живого чату (камертон стилю, не копіюй дослівно):\n\n"
        + BASE_DIALOGUES.format(u=user_name)
        + "\nТак НЕ писати:\n"
        + BAD_EXAMPLES
    )


def learned_examples(good: list[tuple[str, str, str]], bad: list[tuple[str, str, str]]) -> str:
    """Приклади, які позначив сам користувач (/топ і /кринж). Кортеж: (хто, на що, що написав)."""

    def render(items: list[tuple[str, str, str]]) -> str:
        lines = []
        for who, context, text in items:
            before = f"на «{context}» " if context else ""
            lines.append(f"- {who} {before}→ «{text}»")
        return "\n".join(lines)

    blocks = []
    if good:
        blocks.append("Твій друг позначив як ТОП (пиши в такому дусі):\n" + render(good))
    if bad:
        blocks.append("Твій друг позначив як КРИНЖ (ніколи так не пиши):\n" + render(bad))
    return "\n\n".join(blocks)
